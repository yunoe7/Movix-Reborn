import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import test from 'node:test';

const SOURCE = readFileSync(new URL('../userscript/movix.user.js', import.meta.url), 'utf8');
const TV_COPY = readFileSync(
  new URL('../app-tv/app/src/main/assets/extract/movix.user.js', import.meta.url),
  'utf8'
);

function between(source, start, end) {
  const from = source.indexOf(start);
  assert.notEqual(from, -1, `marqueur absent : ${start}`);
  const to = source.indexOf(end, from);
  assert.notEqual(to, -1, `marqueur absent : ${end}`);
  return source.slice(from, to).replace(/\s+/g, ' ').trim();
}

const prefsHandler = (source) => between(
  source,
  'case "SET_EXTRACTION_PREFS": {',
  'case "GET_EXTRACTION_PREFS":'
);

const defaultPrefs = (source) => {
  const from = source.indexOf('const DEFAULT_EXTRACTION_PREFS = {');
  assert.notEqual(from, -1, 'DEFAULT_EXTRACTION_PREFS absent');
  const to = source.indexOf('\n  };', from);
  assert.notEqual(to, -1, 'fin de DEFAULT_EXTRACTION_PREFS absente');
  return source.slice(from, to).replace(/\s+/g, ' ').trim();
};

const nativeGmHandler = (source) => between(
  source,
  '// BEGIN NATIVE GM VALUE CHANGE',
  '// END NATIVE GM VALUE CHANGE'
);

test('la copie TV et le userscript appliquent la même politique de préférences d’extraction', () => {
  assert.equal(prefsHandler(TV_COPY), prefsHandler(SOURCE));
  assert.equal(defaultPrefs(TV_COPY), defaultPrefs(SOURCE));
});

test('la copie TV conserve le correctif de clé gk Fsvid/Vidzy', () => {
  for (const source of [SOURCE, TV_COPY]) {
    assert.match(source, /function requestFsvidVidzyGateKey\(gateUrls\)/);
    assert.match(source, /fsvid: "https:\/\/fsvid\.lol\/gk"/);
    assert.match(source, /withFsvidVidzyGateKey\(/);
  }
});

test('le handler de changement natif applique la même normalisation que SET_EXTRACTION_PREFS', () => {
  const handler = nativeGmHandler(SOURCE);

  assert.match(handler, /addEventListener\("movix:gm-value-changed"/);
  assert.match(handler, /detail\.key !== "movix_extraction_prefs"/);
  assert.match(handler, /gmDeleteValueCompat\("movix_extraction_prefs"\)/);
  assert.match(handler, /gmSetValueCompat\("movix_extraction_prefs", extractionPrefs\)/);
  assert.match(handler, /DEFAULT_EXTRACTION_PREFS\.m3u8/);
  assert.match(handler, /DEFAULT_EXTRACTION_PREFS\.livetv/);
  assert.match(prefsHandler(SOURCE), /DEFAULT_EXTRACTION_PREFS\.m3u8/);
  assert.match(prefsHandler(SOURCE), /DEFAULT_EXTRACTION_PREFS\.livetv/);
});

test('la divergence de version annoncée est explicite dans la copie TV', () => {
  // La copie TV est maintenue à la main et volontairement épinglée en 1.7.3
  // (commit 24770213). Le handler natif ajouté à la source 1.7.9 n'y est donc
  // pas répercuté : l'écart reste documenté au lieu d'être une dérive silencieuse.
  assert.match(TV_COPY, /version: "1\.7\.3"/);
  assert.match(SOURCE, /version: "1\.7\.9"/);
  assert.match(TV_COPY, /Auto-generated by userscript\/build-userscript\.mjs/);
  assert.doesNotMatch(
    TV_COPY,
    /movix:gm-value-changed/,
    'la copie TV 1.7.3 est épinglée : ne pas y recopier le handler 1.7.9',
  );
});
